def _ssl_context() -> ssl.SSLContext:
    """An SSL context that trusts the Bridge's local self-signed certificate.

    The Bridge certificate is local-only and ephemeral, so hostname verification
    is intentionally disabled for ``127.0.0.1``.
    """
    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    return ctx


def _connect(account: Account) -> imaplib.IMAP4:
    """Open and authenticate an IMAP connection for ``account``.

    ``account.security`` selects how the connection is secured:

    - ``"starttls"`` (default): connect plaintext, then upgrade with STARTTLS —
      what Proton Mail Bridge v3 advertises for ``127.0.0.1:1143``.
    - ``"ssl"``: TLS from connection start (older Bridge versions).
    - ``"plain"``: no encryption (localhost only).
    """
    ctx = _ssl_context()
    try:
        if account.security == "ssl":
            conn = imaplib.IMAP4_SSL(
                host=account.host, port=account.port, ssl_context=ctx
            )
        else:
            conn = imaplib.IMAP4(host=account.host, port=account.port)
    except (OSError, socket.error) as exc:
        raise ImapError(
            f"Cannot connect to {account.host}:{account.port} for account "
            f"{account.name!r}. Is Proton Mail Bridge running? ({exc})"
        ) from exc

    if account.security == "starttls":
        try:
            typ, data = conn.starttls(ssl_context=ctx)
            if typ != "OK":
                raise ImapError(
                    f"STARTTLS upgrade failed for {account.name!r}: {typ} {data!r}"
                )
        except imaplib.IMAP4.error as exc:
            raise ImapError(
                f"STARTTLS upgrade failed for {account.name!r} on "
                f"{account.host}:{account.port}. ({exc})"
            ) from exc
        except (OSError, socket.error) as exc:
            raise ImapError(
                f"STARTTLS upgrade failed for {account.name!r}: {exc}"
            ) from exc

    try:
        typ, data = conn.login(account.username, account.password)
        if typ != "OK":
            raise ImapError(
                f"IMAP login failed for {account.username!r}: {typ} {data!r}"
            )
    except imaplib.IMAP4.error as exc:
        raise ImapError(
            f"IMAP login failed for {account.username!r} on account "
            f"{account.name!r}. Check that the username is the Proton address "
            f"and the password is the one generated by Proton Mail Bridge. ({exc})"
        ) from exc
    return conn


def _disconnect(conn: imaplib.IMAP4) -> None:
    """Best-effort close + logout so connections are never leaked."""
    try:
        try:
            conn.close()
        except imaplib.IMAP4.error:
            pass
        conn.logout()
    except (imaplib.IMAP4.error, OSError):
        pass


def _quote_mailbox(name: str) -> str:
    """Quote a mailbox name for SELECT, escaping embedded quotes/backslashes."""
    escaped = name.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _decode_header_value(value: str | None) -> str:
    """Decode an RFC 2047 encoded header into a single string."""
    if not value:
        return ""
    try:
        dec = decode_header(value)
        return str(make_header(dec))
    except Exception:
        return value


def _strip_tags(html: str) -> str:
    """Very small HTML->text for rendering when no text/plain exists."""
    text = re.sub(r"(?is)<(script|style).*?>.*?</\1>", "", html)
    text = re.sub(r"(?is)<br\s*/?>", "\n", text)
    text = re.sub(r"(?i)</p\s*>", "\n\n", text)
    text = re.sub(r"(?s)<[^>]+>", "", text)
    import html as html_mod

    return html_mod.unescape(text).strip()


_FOLDER_RE = re.compile(
    r'^\((?P<flags>[^)]*)\)\s+"(?P<delim>[^"]*)"\s+(?P<name>.*)$'
)


def _parse_mailbox_name(raw: str) -> str:
    """Unquote a mailbox name returned by LIST."""
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == '"' and raw[-1] == '"':
        return raw[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    return raw


def _select(conn: imaplib.IMAP4, folder: str) -> int:
    """SELECT a mailbox and return the EXISTS message count."""
    typ, data = conn.select(_quote_mailbox(folder))
    if typ != "OK":
        raise ImapError(
            f"Could not select folder {folder!r}: {typ} {data!r}"
        )
    try:
        return int(data[0])
    except (ValueError, IndexError) as exc:
        raise ImapError(f"Unexpected SELECT response for {folder!r}: {data!r}") from exc


def _parse_meta(meta: bytes) -> dict:
    """Extract UID/FLAGS/INTERNALDATE/RFC822.SIZE from a FETCH metadata line."""
    s = meta.decode("utf-8", errors="replace")
    out: dict = {}
    m = re.search(r"\bUID\s+(\d+)", s)
    if m:
        out["uid"] = int(m.group(1))
    m = re.search(r"FLAGS\s+\(([^)]*)\)", s)
    if m:
        out["flags"] = [f.strip() for f in m.group(1).split() if f.strip()]
    else:
        out["flags"] = []
    m = re.search(r'INTERNALDATE\s+"([^"]*)"', s)
    if m:
        out["internaldate"] = m.group(1)
    m = re.search(r"RFC822\.SIZE\s+(\d+)", s)
    if m:
        out["size"] = int(m.group(1))
    return out


def _headers_to_dict(header_bytes: bytes) -> dict[str, str]:
    """Parse a block of raw headers into a dict of decoded header values."""
    msg = email.message_from_bytes(header_bytes)
    out: dict[str, str] = {}
    seen: dict[str, list[str]] = {}
    for key, value in msg.items():
        decoded = _decode_header_value(value)
        seen.setdefault(key.lower(), []).append(decoded)
    for key, values in seen.items():
        out[key] = ", ".join(values)
    return out


def _parse_fetch(data: Iterable) -> list[dict]:
    """Parse imaplib FETCH responses into per-message dicts.

    Each flagged message yields a tuple ``(meta_bytes, literal_bytes)`` where
    ``literal_bytes`` is the PEEKed header body. We pair them and also merge any
    continuation items, returning a list ordered by sequence number.
    """
    results: list[dict] = []
    for item in data:
        if isinstance(item, tuple) and len(item) == 2:
            meta, payload = item
            info = _parse_meta(meta)
            info["headers"] = payload
            results.append(info)
    return results


