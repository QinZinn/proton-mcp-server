"""IMAP access to Proton Mail through Proton Mail Bridge.

Proton Mail Bridge exposes a local IMAP server (default ``127.0.0.1:1143``).
Bridge v3 advertises STARTTLS on localhost (it manages the encrypted connection
to Proton's servers itself); ``security="starttls"`` is therefore the default
on accounts. Set ``security="ssl"`` for TLS-from-start (older Bridge versions)
or ``security="plain"`` to skip encryption (localhost only). For the local
self-signed certificate presented by the Bridge, TLS verification is disabled.
Authentication uses the Proton account address and a bridge-generated
password. This module wraps ``imaplib`` (stdlib) to provide the read
operations the MCP server exposes.

Every public function opens a fresh connection, performs its operation, then
logs out — keeping tools stateless and avoiding stale mailbox selections
between calls. Blocking ``imaplib`` calls run inside the MCP server's worker
threadpool, so synchronous code is fine here.
"""

from __future__ import annotations

import email
import email.utils
import imaplib
import re
import socket
import ssl
from dataclasses import dataclass
from email.header import decode_header, make_header
from email.message import Message
from typing import Iterable

from .config import Account


class ImapError(Exception):
    """Raised on IMAP connection or protocol errors surfaced to the agent."""


@dataclass
class FolderInfo:
    name: str
    delimiter: str
    flags: list[str]
    selectable: bool


@dataclass
class MessageSummary:
    uid: int
    folder: str
    subject: str
    sender: str
    to: str
    date: str
    flags: list[str]
    size: int
    snippet: str = ""


@dataclass
class GetMessage:
    uid: int
    folder: str
    headers: dict[str, str]
    body_text: str | None
    body_html: str | None
    attachments: list[dict]
    raw_size: int


