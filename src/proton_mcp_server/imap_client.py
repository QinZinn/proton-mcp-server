def list_folders(account: Account) -> list[FolderInfo]:
    """List all mailboxes available for ``account``."""
    conn = _connect(account)
    try:
        typ, data = conn.list()
        if typ != "OK":
            raise ImapError(f"LIST failed: {typ} {data!r}")
        folders: list[FolderInfo] = []
        for item in data:
            if isinstance(item, bytes):
                item = item.decode("utf-8", errors="replace")
            elif not isinstance(item, str):
                continue
            m = _FOLDER_RE.match(item.strip())
            if not m:
                continue
            flags = m.group("flags").split()
            name = _parse_mailbox_name(m.group("name"))
            selectable = r"\Noselect" not in flags
            folders.append(
                FolderInfo(
                    name=name,
                    delimiter=m.group("delim"),
                    flags=flags,
                    selectable=selectable,
                )
            )
        return folders
    finally:
        _disconnect(conn)


def _summaries_from_fetch(
    items: list[dict], folder: str, include_snippet: bool = False
) -> list[MessageSummary]:
    summaries: list[MessageSummary] = []
    for info in items:
        headers = _headers_to_dict(info.get("headers", b""))
        summaries.append(
            MessageSummary(
                uid=int(info.get("uid", 0) or 0),
                folder=folder,
                subject=headers.get("subject", "(no subject)") or "(no subject)",
                sender=headers.get("from", headers.get("sender", "")) or "",
                to=headers.get("to", "") or "",
                date=info.get("internaldate", headers.get("date", "")) or "",
                flags=info.get("flags", []),
                size=int(info.get("size", 0) or 0),
            )
        )
    # Newest first by INTERNALDATE, falling back to UID.
    summaries.sort(key=lambda s: s.date, reverse=True)
    return summaries


def list_messages(
    account: Account,
    folder: str = "INBOX",
    limit: int = 20,
    page: int = 0,
) -> list[MessageSummary]:
    """Return recent messages in ``folder``.

    Fetches a sequence window of ``limit`` envelopes (newest block first by
    IMAP sequence order), then re-sorts by internal date so the agent sees the
    most recent messages first. Pagination walks backwards through sequence
    space. Only envelope-level headers are transferred, regardless of mailbox
    size.
    """
    if limit <= 0:
        return []
    conn = _connect(account)
    try:
        exists = _select(conn, folder)
        if exists == 0:
            return []
        end = exists - page * limit
        start = max(1, end - limit + 1)
        if end < 1:
            return []
        range_str = f"{start}:{end}"
        typ, data = conn.fetch(
            range_str,
            "(UID FLAGS INTERNALDATE RFC822.SIZE "
            "BODY.PEEK[HEADER.FIELDS (SUBJECT FROM SENDER TO CC DATE MESSAGE-ID)])",
        )
        if typ != "OK":
            raise ImapError(f"FETCH failed: {typ} {data!r}")
        items = _parse_fetch(data)
        return _summaries_from_fetch(items, folder)
    finally:
        _disconnect(conn)


_CRITERIA_FIELDS = {
    "subject": "SUBJECT",
    "from": "FROM",
    "sender": "SENDER",
    "to": "TO",
    "cc": "CC",
    "bcc": "BCC",
    "body": "BODY",
    "text": "TEXT",
}


def search_messages(
    account: Account,
    query: str,
    folder: str = "INBOX",
    criteria: str = "subject",
    limit: int = 50,
) -> list[MessageSummary]:
    """Search messages in ``folder`` by a single IMAP field criterion.

    ``criteria`` is one of: subject, from, sender, to, cc, bcc, body, text.
    Results are capped at ``limit`` and sorted newest-first by internal date.
    """
    field = _CRITERIA_FIELDS.get(criteria.lower())
    if not field:
        raise ImapError(
            f"Unknown search criteria {criteria!r}. Valid: "
            + ", ".join(sorted(_CRITERIA_FIELDS))
        )
    if not query.strip():
        raise ImapError("Search query must not be empty.")

    # Escape for IMAP quoted-string: backslash and double-quote.
    escaped = query.replace("\\", "\\\\").replace('"', '\\"')
    quoted = f'"{escaped}"'

    conn = _connect(account)
    try:
        _select(conn, folder)
        typ, data = conn.search(None, field, quoted)
        if typ != "OK":
            raise ImapError(f"SEARCH failed: {typ} {data!r}")
        if not data or not data[0]:
            return []
        seq_nums = data[0].split()
        # SERVER side result; keep the newest `limit` by sequence then fetch.
        seq_nums = seq_nums[-limit:] if limit < len(seq_nums) else seq_nums
        range_str = ",".join(s.decode() if isinstance(s, bytes) else str(s) for s in seq_nums)
        if not range_str:
            return []
        typ, fdata = conn.fetch(
            range_str,
            "(UID FLAGS INTERNALDATE RFC822.SIZE "
            "BODY.PEEK[HEADER.FIELDS (SUBJECT FROM SENDER TO CC DATE MESSAGE-ID)])",
        )
        if typ != "OK":
            raise ImapError(f"FETCH after SEARCH failed: {typ} {fdata!r}")
        items = _parse_fetch(fdata)
        summaries = _summaries_from_fetch(items, folder)
        return summaries[:limit]
    finally:
        _disconnect(conn)


def _walk_message(msg: Message) -> tuple[str | None, str | None, list[dict]]:
    """Walk a multipart message returning (text_plain, text_html, attachments)."""
    text_plain: str | None = None
    text_html: str | None = None
    attachments: list[dict] = []

    for part in msg.walk():
        if part.is_multipart():
            continue
        content_disposition = (part.get_content_disposition() or "").lower()
        filename = part.get_filename()
        decoded_filename = _decode_header_value(filename) if filename else None

        if content_disposition == "attachment" or (
            filename and content_disposition not in ("inline", "")
        ):
            payload = part.get_payload(decode=True) or b""
            attachments.append(
                {
                    "filename": decoded_filename or "(unnamed)",
                    "content_type": part.get_content_type(),
                    "size": len(payload),
                }
            )
            continue

        ctype = part.get_content_type()
        if ctype == "text/plain" and text_plain is None:
            payload = part.get_payload(decode=True) or b""
            charset = part.get_content_charset() or "utf-8"
            try:
                text_plain = payload.decode(charset, errors="replace")
            except LookupError:
                text_plain = payload.decode("utf-8", errors="replace")
        elif ctype == "text/html" and text_html is None:
            payload = part.get_payload(decode=True) or b""
            charset = part.get_content_charset() or "utf-8"
            try:
                text_html = payload.decode(charset, errors="replace")
            except LookupError:
                text_html = payload.decode("utf-8", errors="replace")

    return text_plain, text_html, attachments


def get_message(account: Account, uid: int, folder: str = "INBOX") -> GetMessage:
    """Fetch a full message by UID and parse headers, body, and attachments."""
    if uid <= 0:
        raise ImapError("uid must be a positive integer.")

    conn = _connect(account)
    try:
        _select(conn, folder)
        typ, data = conn.uid("fetch", str(uid), "(RFC822.SIZE RFC822)")
        if typ != "OK":
            raise ImapError(f"UID FETCH failed: {typ} {data!r}")

        raw: bytes | None = None
        raw_size = 0
        for item in data:
            if isinstance(item, tuple) and len(item) == 2:
                meta, payload = item
                m = re.search(r"RFC822\.SIZE\s+(\d+)", meta.decode("utf-8", "replace"))
                if m:
                    raw_size = int(m.group(1))
                if payload:
                    raw = payload
                    break
        if raw is None:
            raise ImapError(
                f"Message with UID {uid} not found in folder {folder!r}."
            )

        msg = email.message_from_bytes(raw)
        headers: dict[str, str] = {}
        for key, value in msg.items():
            headers[key.lower()] = _decode_header_value(value)

        text_plain, text_html, attachments = _walk_message(msg)

        return GetMessage(
            uid=uid,
            folder=folder,
            headers=headers,
            body_text=text_plain,
            body_html=text_html,
            attachments=attachments,
            raw_size=raw_size or len(raw),
        )
    finally:
        _disconnect(conn)